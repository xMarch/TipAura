    // The catalog icon an `icon` value names; null for a file path or an unknown name. Names are
    // lower-case kebab case as on lucide.dev; the prefix and name match case-insensitively.
    internal static Icon? Find(string? value)
    {
        if (!IsIcon(value)) return null;
        string name = value!.Substring(Prefix.Length).Trim().ToLowerInvariant();
        int index = Array.BinarySearch(Icons, new Icon(name, '\0', 0), NameOrder.Instance);
        return index >= 0 ? Icons[index] : null;
    }

    // True for any `lucide:` value, known or not; such a value is never a file path.
    internal static bool IsIcon(string? value) => value is not null && value.StartsWith(Prefix, StringComparison.OrdinalIgnoreCase);

